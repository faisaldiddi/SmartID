export function getTemplateCardState(tpl: TemplateDesign): CardState {
  const orgName = tpl.header?.orgName || tpl.name.toUpperCase();
  return {
    ...DEFAULT_CARD_STATE,
    templateId: tpl.id,
    orientation: tpl.orientation,
    hasBack: tpl.hasBack,
    colors: { ...tpl.colors },
    pattern: tpl.pattern,
    fontFamily: tpl.fontFamily,
    header: {
      ...DEFAULT_CARD_STATE.header,
      orgName,
      subtitle: tpl.description || DEFAULT_CARD_STATE.header.subtitle,
      bgColor: tpl.colors.headerBg,
    },
    footer: {
      ...DEFAULT_CARD_STATE.footer,
      bgColor: tpl.colors.footerBg,
    },
    details: {
      ...DEFAULT_CARD_STATE.details,
      fullName: 'Alexander Wright',
      uniqueId: `ID-${Math.floor(1000 + Math.random() * 9000)}`,
      department: tpl.category,
      designation: 
        tpl.category === 'Corporate' ? 'Senior Executive' :
        tpl.category === 'Hospital' ? 'Clinical Specialist' :
        tpl.category === 'College' ? 'Research Fellow' :
        tpl.category === 'Security' ? 'Security Operations' :
        tpl.category === 'Event' ? 'VIP Delegate' : 'Staff Member',
    },
    customTemplateName: tpl.name,
  };
}

